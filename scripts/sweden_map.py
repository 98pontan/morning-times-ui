"""Generate src/lib/swedenMap.ts (SVG paths for the 21 counties) from a county GeoJSON.

Source: https://github.com/okfse/sweden-geojson (swedish_regions.geojson). Its l_id is the county
code, which is also SMHI's warning-area id for the county, so the map and the API share ids.

    curl -sLo /tmp/regions.geojson https://raw.githubusercontent.com/okfse/sweden-geojson/master/swedish_regions.geojson
    python3 scripts/sweden_map.py /tmp/regions.geojson > src/lib/swedenMap.ts

The projection is equirectangular with x scaled by cos(62°), which is close enough for Sweden;
src/lib/swedenMap.ts exports the same projection (project()) for placing labels and arrows.
"""

import json
import math
import sys

LON0, LAT1 = 10.5, 69.3      # top-left corner (degrees)
KX = math.cos(math.radians(62))
SCALE = 72.0                  # SVG units per degree of latitude
PAD = 0


def project(lon: float, lat: float) -> tuple[float, float]:
    return ((lon - LON0) * KX * SCALE + PAD, (LAT1 - lat) * SCALE + PAD)


def ring_path(ring: list[list[float]]) -> str:
    out, last = [], None
    for lon, lat in ring:
        x, y = project(lon, lat)
        point = (round(x, 1), round(y, 1))
        if point != last:
            out.append(f"{point[0]:g},{point[1]:g}")
            last = point
    return "M" + "L".join(out) + "Z"


def main(path: str) -> None:
    data = json.load(open(path, encoding="utf-8"))
    counties = []
    max_x = max_y = 0.0
    for feature in data["features"]:
        geometry = feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        d = "".join(ring_path(ring) for polygon in polygons for ring in polygon)
        for polygon in polygons:
            for lon, lat in polygon[0]:
                x, y = project(lon, lat)
                max_x, max_y = max(max_x, x), max(max_y, y)
        counties.append((feature["properties"]["l_id"], feature["properties"]["name"], d))
    counties.sort()

    print("// Generated by scripts/sweden_map.py from okfse/sweden-geojson. Do not edit by hand.")
    print("// id = county code = SMHI warning-area id.")
    print(f"export const MAP_WIDTH = {math.ceil(max_x) + PAD};")
    print(f"export const MAP_HEIGHT = {math.ceil(max_y) + PAD};")
    print()
    print("/** Same projection as the paths: degrees -> SVG units. */")
    print("export function project(lat: number, lon: number): [number, number] {")
    print(f"  return [(lon - {LON0}) * {KX:.6f} * {SCALE} + {PAD}, ({LAT1} - lat) * {SCALE} + {PAD}];")
    print("}")
    print()
    print("export const COUNTIES: { id: number; name: string; d: string }[] = [")
    for cid, name, d in counties:
        print(f"  {{ id: {cid}, name: {json.dumps(name, ensure_ascii=False)}, d: {json.dumps(d)} }},")
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
